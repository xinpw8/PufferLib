def _validate_preflight_report(
    report_path: Path,
    motion: MotionSpec,
    exit_code: int,
    config: SuiteConfig,
    rek_traces: Sequence[Path],
    sim_trace: Path,
) -> tuple[str, dict[str, Any]]:
    if not report_path.is_file():
        return "insufficient_evidence", {
            "blockers": ["comparison_report_not_produced"],
            "tool_exit_code": exit_code,
        }
    report = _load_object(report_path, "comparison report")
    verdict = report.get("verdict")
    if report.get("schema") != COMPARISON_SCHEMA or not isinstance(verdict, dict):
        raise SuiteError("comparison tool emitted an invalid report schema")
    if report.get("command_identity") != motion.command_identity:
        raise SuiteError("comparison report command identity changed")
    state = verdict.get("state")
    passed = verdict.get("passed")
    expected_exit = {"passed": 0, "failed": 1, "insufficient_evidence": 2}
    if state not in expected_exit or expected_exit[state] != exit_code:
        raise SuiteError(
            f"comparison report state {state!r} disagrees with exit {exit_code}"
        )
    expected_passed = {"passed": True, "failed": False, "insufficient_evidence": None}
    if passed is not expected_passed[state]:
        raise SuiteError("comparison report verdict state/passed fields disagree")
    inputs = report.get("inputs")
    if not isinstance(inputs, dict):
        raise SuiteError("comparison report has no bound input identities")
    reference = inputs.get("reference")
    repeats = inputs.get("repeats")
    candidate = inputs.get("candidate")
    if not isinstance(reference, dict) or not isinstance(repeats, list):
        raise SuiteError("comparison report REK input identities are incomplete")
    if not isinstance(candidate, dict):
        raise SuiteError("comparison report simulator identity is incomplete")
    rek_inputs = [reference, *repeats]
    if len(rek_inputs) != len(rek_traces):
        raise SuiteError("comparison report changed the REK repeat count")
    for index, (identity, path) in enumerate(zip(rek_inputs, rek_traces)):
        if (
            identity.get("path") != str(path.resolve())
            or identity.get("sha256") != _sha256(path)
            or identity.get("format") != "REKTRACE.v1"
            or identity.get("source") != "rek"
            or identity.get("command_identity") != motion.command_identity
        ):
            raise SuiteError(f"comparison report REK input {index} was substituted")
    if (
        candidate.get("path") != str(sim_trace.resolve())
        or candidate.get("sha256") != _sha256(sim_trace)
        or candidate.get("format") != TRACE_SCHEMA
        or candidate.get("source") != "clone:rek_fight_engineai"
        or candidate.get("command_identity") != motion.command_identity
        or candidate.get("execution_state") != "simulated"
    ):
        raise SuiteError("comparison report simulator input was substituted")
    all_inputs = [*rek_inputs, candidate]
    for key in ("capture_id", "run_id", "build_fingerprint"):
        values = [identity.get(key) for identity in all_inputs]
        if any(not isinstance(value, str) or not value for value in values):
            raise SuiteError(f"comparison report has missing input {key}")
        if key != "build_fingerprint" and len(set(values)) != len(values):
            raise SuiteError(f"comparison report input {key} values are not distinct")
        if key == "build_fingerprint" and len(set(values)) != 1:
            raise SuiteError("comparison report inputs identify different REK builds")
    alignment = report.get("alignment")
    expected_frames = round((config.end_s - config.start_s) * config.comparison_fps) + 1
    if (
        not isinstance(alignment, dict)
        or alignment.get("source") != "explicit_uniform_timebase"
        or alignment.get("fps") != config.comparison_fps
        or alignment.get("start_relative_time_s") != config.start_s
        or alignment.get("end_relative_time_s") != config.end_s
        or alignment.get("frame_count") != expected_frames
        or alignment.get("interpolation_used") is not False
        or alignment.get("sample_selection")
        != "nearest_distinct_measured_sample_no_interpolation"
        or alignment.get("declared_maximum_timestamp_uncertainty_s") != 0.0
    ):
        raise SuiteError("comparison report did not preserve the exact explicit grid")
    if expected_frames < 2:
        raise SuiteError("comparison report contains fewer than two frames")
    if state == "passed" and any(
        identity.get("execution_state") != "measured_executed"
        for identity in rek_inputs
    ):
        raise SuiteError("passing report does not contain measured-executed REK inputs")
    screen = report.get("screen_metric")
    if (
        not isinstance(screen, dict)
        or screen.get("required") is not True
        or (state == "passed" and screen.get("comparable") is not True)
    ):
        raise SuiteError("comparison report bypassed the common screen-frame gate")
    return state, report


def _validate_generated_anchor(
    anchor_path: Path,
    trace_path: Path,
    video_path: Path,
    capture_dir: Path,
    marker_contract_path: Path,
    capture_schema: str,
    command_identity: str,
) -> dict[str, Any]:
    anchor = _load_object(anchor_path, "generated video clock anchor")
    if anchor.get("schema") != ANCHOR_SCHEMA:
        raise SuiteError("generated anchor has the wrong schema")
    if anchor.get("trace_sha256") != _sha256(trace_path):
        raise SuiteError("generated anchor is not bound to the compared trace")
    if anchor.get("video_sha256") != _sha256(video_path):
        raise SuiteError("generated anchor is not bound to the explicit video")
    if anchor.get("command_identity") != command_identity:
        raise SuiteError("generated anchor has the wrong command identity")
    if anchor.get("schedule_run_id") != anchor.get("run_id"):
        raise SuiteError("generated anchor run identifiers disagree")
    measurement = anchor.get("measurement")
    marker = anchor.get("marker_observation")
    verified = anchor.get("verified_artifacts")
    if not isinstance(measurement, dict):
        raise SuiteError("generated anchor has no measurement record")
    if measurement.get("state") != "measured":
        raise SuiteError("generated anchor is not measured")
    if measurement.get("method") != MEASURED_ANCHOR_METHOD:
        raise SuiteError("diagnostic or manual video clock anchor refused")
    if not isinstance(marker, dict) or marker.get("transition") != MEASURED_MARKER_TRANSITION:
        raise SuiteError("generated anchor lacks the exact rendered-marker transition")
    if not isinstance(verified, dict):
        raise SuiteError("generated anchor lacks verified artifacts")
    source_capture = anchor.get("source_capture")
    manifest_path = capture_dir / "capture.manifest.json"
    if (
        not isinstance(source_capture, dict)
        or source_capture.get("capture_schema") != capture_schema
        or source_capture.get("capture_manifest_sha256") != _sha256(manifest_path)
        or not isinstance(source_capture.get("capture_id"), str)
        or not source_capture.get("capture_id")
    ):
        raise SuiteError("generated anchor is not bound to the explicit capture")
    binding = anchor.get("capture_binding")
    expected_binding = {
        "marker_contract_schema": "rek.rendered_command_marker.v1",
        "marker_contract_sha256": _sha256(marker_contract_path),
        "trace_sha256": _sha256(trace_path),
        "capture_id": source_capture["capture_id"],
        "schedule_run_id": anchor.get("schedule_run_id"),
        "command_identity": command_identity,
        "render_binding": (
            "first_post_marker_frame_is_first_rendered_frame_after_command_edge"
        ),
    }
    if not isinstance(binding, dict) or any(
        binding.get(key) != value for key, value in expected_binding.items()
    ):
        raise SuiteError("generated anchor capture binding is incomplete or swapped")
    published = verified.get("published_video")
    if not isinstance(published, dict):
        raise SuiteError("generated anchor lacks its published-video binding")
    if Path(str(published.get("path"))).resolve() != video_path.resolve():
        raise SuiteError("capture encoded video differs from the explicit video path")
    return anchor


def _validate_final_report(
    report_path: Path,
    clip_path: Path,
    motion: MotionSpec,
    config: SuiteConfig,
    rek_traces: Sequence[Path],
    sim_trace: Path,
    rek_video_path: Path,
    sim_video_path: Path,
) -> dict[str, Any]:
    state, report = _validate_preflight_report(
        report_path, motion, 0, config, rek_traces, sim_trace
    )
    if state != "passed":
        raise SuiteError("final report is not a passing exact-grid comparison")
    verdict = report.get("verdict")
    video = report.get("video")
    if report.get("schema") != COMPARISON_SCHEMA:
        raise SuiteError("final report has the wrong schema")
    if report.get("command_identity") != motion.command_identity:
        raise SuiteError("final report has the wrong command identity")
    if not isinstance(verdict, dict) or verdict.get("state") != "passed":
        raise SuiteError("final comparison did not pass")
    if verdict.get("passed") is not True or verdict.get("blockers") != []:
        raise SuiteError("final comparison is not an unblocked passing verdict")
    required_metrics = ["root_position", "root_yaw", "screen_root"]
    metrics = report.get("metrics")
    if not isinstance(metrics, dict):
        raise SuiteError("final report has no metrics")
    for name in required_metrics:
        metric = metrics.get(name)
        if (
            not isinstance(metric, dict)
            or metric.get("passed") is not True
            or metric.get("failed_frame_count") != 0
        ):
            raise SuiteError(f"final {name} metric did not pass every measured frame")
    alignment = report.get("alignment")
    if (
        not isinstance(alignment, dict)
        or alignment.get("interpolation_used") is not False
        or alignment.get("sample_selection")
        != "nearest_distinct_measured_sample_no_interpolation"
    ):
        raise SuiteError("final comparison did not use distinct measured samples")
    if (
        not isinstance(video, dict)
        or video.get("status") != "rendered"
        or video.get("evidence_grade") != "acceptance"
        or video.get("supports_parity_verdict") is not True
        or video.get("alignment_basis") != "measured_video_clock_anchors"
        or video.get("layout") != "side-by-side"
        or video.get("fps") != config.video_fps
    ):
        raise SuiteError("paired video is not acceptance-grade measured alignment")
    expected_frames = (
        math.floor((config.end_s - config.start_s) * config.video_fps + 1e-12)
        + 1
    )
    if video.get("frame_count") != expected_frames:
        raise SuiteError("paired video does not cover every requested video frame")
    reference_video = video.get("reference_video")
    candidate_video = video.get("candidate_video")
    if not isinstance(reference_video, dict) or not isinstance(candidate_video, dict):
        raise SuiteError("paired video source identities are absent")
    if (
        reference_video.get("sha256") != _sha256(rek_video_path)
        or candidate_video.get("sha256") != _sha256(sim_video_path)
        or reference_video.get("sha256") == candidate_video.get("sha256")
    ):
        raise SuiteError("paired video sources are swapped or identical")
    reference_probe = reference_video.get("probe")
    candidate_probe = candidate_video.get("probe")
    if not isinstance(reference_probe, dict) or not isinstance(candidate_probe, dict):
        raise SuiteError("paired video source probes are absent")
    source_geometry = (
        reference_probe.get("width"),
        reference_probe.get("height"),
        reference_probe.get("r_frame_rate"),
    )
    if source_geometry != (
        candidate_probe.get("width"),
        candidate_probe.get("height"),
        candidate_probe.get("r_frame_rate"),
    ):
        raise SuiteError("paired video would rescale or rate-convert a source")
    if not math.isclose(
        _rate_hz(source_geometry[2], "source video frame rate"),
        config.video_fps,
        rel_tol=0.0,
        abs_tol=1e-12,
    ):
        raise SuiteError("paired video output rate differs from its source videos")
    output = video.get("output")
    if not isinstance(output, dict) or not clip_path.is_file():
        raise SuiteError("paired video output is absent")
    if output.get("sha256") != _sha256(clip_path):
        raise SuiteError("paired video SHA-256 does not match its report")
    if Path(str(output.get("path"))).resolve() != clip_path.resolve():
        raise SuiteError("paired video path does not match its report")
    output_probe = output.get("probe")
    if (
        not isinstance(output_probe, dict)
        or output_probe.get("frame_count") != expected_frames
    ):
        raise SuiteError("paired video probe does not prove the requested frame count")
    return report


def _capture_manifest_identity(
    capture: Path,
    expected_schema: str,
    video_path: Path,
    marker_contract_path: Path,
    command_identity: str,
) -> dict[str, Any]:
    manifest_path = _file(capture / "capture.manifest.json", "capture manifest")
    manifest = _load_object(manifest_path, "capture manifest")
    if manifest.get("schema") != expected_schema or manifest.get("status") != "complete":
        raise SuiteError(f"capture is not a complete {expected_schema} artifact")
    capture_id = manifest.get("capture_id")
    request = manifest.get("request")
    result = manifest.get("result")
    binding = manifest.get("binding")
    artifacts = manifest.get("artifacts")
    if not isinstance(capture_id, str) or not capture_id:
        raise SuiteError("capture manifest has no capture_id")
    if not all(isinstance(item, dict) for item in (request, result, binding, artifacts)):
        raise SuiteError("capture manifest is missing request/result/binding/artifacts")
    assert isinstance(request, dict)
    assert isinstance(result, dict)
    assert isinstance(binding, dict)
    assert isinstance(artifacts, dict)
    if (
        request.get("synthetic_frame_duplication") is not False
        or isinstance(request.get("fps_numerator"), bool)
        or not isinstance(request.get("fps_numerator"), int)
        or request.get("fps_numerator") <= 0
        or isinstance(request.get("fps_denominator"), bool)
        or not isinstance(request.get("fps_denominator"), int)
        or request.get("fps_denominator") <= 0
        or isinstance(request.get("expected_frame_count"), bool)
        or not isinstance(request.get("expected_frame_count"), int)
        or request.get("expected_frame_count") < 2
    ):
        raise SuiteError("capture request does not prove a non-synthetic timebase")
    if expected_schema == SIM_CAPTURE_SCHEMA and (
        request.get("sample_interpolation_used") is not False
        or request.get("frame_selection")
        != "exact_measured_physics_tick_modulo_stride"
    ):
        raise SuiteError("simulator capture is not selected from exact physics samples")
    expected_count = request["expected_frame_count"]
    width = result.get("width_px")
    height = result.get("height_px")
    if (
        result.get("actual_frame_count") != expected_count
        or isinstance(width, bool)
        or not isinstance(width, int)
        or width <= 0
        or width % 2
        or isinstance(height, bool)
        or not isinstance(height, int)
        or height <= 0
        or height % 2
    ):
        raise SuiteError("capture result has invalid frame count or video geometry")
    expected_binding = {
        "marker_contract_schema": "rek.rendered_command_marker.v1",
        "marker_contract_sha256": _sha256(marker_contract_path),
        "capture_id": capture_id,
        "command_identity": command_identity,
        "render_binding": (
            "first_post_marker_frame_is_first_rendered_frame_after_command_edge"
        ),
    }
    if any(binding.get(key) != value for key, value in expected_binding.items()):
        raise SuiteError("capture manifest binding differs from the selected motion")
    for key in ("trace_sha256", "producer_sha256"):
        if not isinstance(binding.get(key), str) or not SHA256_PATTERN.fullmatch(
            binding[key]
        ):
            raise SuiteError(f"capture manifest binding has no valid {key}")
    if not isinstance(binding.get("schedule_run_id"), str) or not binding.get(
        "schedule_run_id"
    ):
        raise SuiteError("capture manifest binding has no schedule_run_id")
    marker_contract = _load_object(marker_contract_path, "marker contract")
    producer_record = marker_contract.get("producer")
    if not isinstance(producer_record, dict):
        raise SuiteError("marker contract has no producer artifact")
    producer = _artifact_from_provenance(
        marker_contract_path,
        producer_record,
        "path",
        "sha256",
        "marker contract producer",
    )
    if producer["sha256"] != binding["producer_sha256"]:
        raise SuiteError("capture binding and marker producer SHA-256 differ")
    if expected_schema == SIM_CAPTURE_SCHEMA:
        expected_sim_producer = (
            Path(__file__).resolve().parent.parent.parent
            / "rek_fight"
            / "capture_motion_video.py"
        )
        if producer["sha256"] != _sha256(expected_sim_producer):
            raise SuiteError(
                "simulator capture marker was not produced by capture_motion_video.py"
            )
    encoded = artifacts.get("encoded_video")
    if not isinstance(encoded, dict):
        raise SuiteError("capture manifest has no encoded video artifact")
    raw_video_path = encoded.get("path")
    if not isinstance(raw_video_path, str) or not raw_video_path:
        raise SuiteError("capture manifest encoded video path is absent")
    published = (capture / raw_video_path).resolve()
    if published != video_path.resolve() or encoded.get("sha256") != _sha256(video_path):
        raise SuiteError("capture manifest does not bind the explicit motion video")
    if result.get("encoded_video_sha256") != _sha256(video_path):
        raise SuiteError("capture result does not bind the explicit motion video")
    return {
        **_identity(manifest_path),
        "schema": expected_schema,
        "capture_id": capture_id,
        "schedule_run_id": binding["schedule_run_id"],
        "command_identity": command_identity,
        "fps_numerator": request["fps_numerator"],
        "fps_denominator": request["fps_denominator"],
        "frame_count": expected_count,
        "width_px": width,
        "height_px": height,
        "binding": binding,
    }


def validate_config(config: SuiteConfig) -> SuiteConfig:
    if len(config.rek_runs) < 3:
        raise SuiteError("at least three explicit REK v6 runs are required")
    raw_paths = [_file(run.raw_trace, f"REK run {index} raw trace")
                 for index, run in enumerate(config.rek_runs)]
    transcript_paths = [
        _file(run.bridge_transcript, f"REK run {index} bridge transcript")
        for index, run in enumerate(config.rek_runs)
    ]
    if len({os.path.normcase(str(path)) for path in raw_paths}) != len(raw_paths):
        raise SuiteError("REK raw trace paths must be distinct")
    if len({_sha256(path) for path in raw_paths}) != len(raw_paths):
        raise SuiteError("REK raw trace contents must be distinct captures")
    if len({os.path.normcase(str(path)) for path in transcript_paths}) != len(
        transcript_paths
    ):
        raise SuiteError("REK bridge transcript paths must be distinct")
    if len({_sha256(path) for path in transcript_paths}) != len(transcript_paths):
        raise SuiteError("REK bridge transcript contents must be distinct captures")
    output = config.output_dir.expanduser().absolute()
    if output.exists() or output.is_symlink():
        raise SuiteError(f"refusing to overwrite output directory {output}")
    _finite(config.start_s, "start_s")
    _finite(config.end_s, "end_s")
    if config.end_s <= config.start_s:
        raise SuiteError("end_s must be later than start_s")
    if config.start_s >= 0.0:
        raise SuiteError("comparison window must include measured pre-edge state")
    comparison_fps = _finite(
        config.comparison_fps, "comparison_fps", positive=True
    )
    uncertainty = _finite(
        config.maximum_timestamp_uncertainty_s,
        "maximum_timestamp_uncertainty_s",
    )
    if uncertainty != 0.0:
        raise SuiteError(
            "maximum_timestamp_uncertainty_s must be zero for exact-grid parity"
        )
    _finite(config.video_fps, "video_fps", positive=True)
    if config.accept_at not in {"median", "p95", "p99", "max"}:
        raise SuiteError("accept_at is unsupported")
    if config.video_layout != "side-by-side":
        raise SuiteError("video_layout must be side-by-side without visual blending")
    if config.screen_required is not True:
        raise SuiteError("the common measured screen-frame gate is mandatory")
    if not config.rek_pilot or not config.sim_pilot:
        raise SuiteError("both pilot selectors must be explicit non-empty strings")
    exact_maps = {
        "rek_captures": _mapping(config.rek_captures.items(), "REK captures"),
        "rek_videos": _mapping(config.rek_videos.items(), "REK videos"),
        "rek_marker_contracts": _mapping(
            config.rek_marker_contracts.items(), "REK marker contracts"
        ),
        "sim_traces": _mapping(config.sim_traces.items(), "simulator traces"),
        "sim_captures": _mapping(
            config.sim_captures.items(), "simulator captures"
        ),
        "sim_videos": _mapping(config.sim_videos.items(), "simulator videos"),
        "sim_marker_contracts": _mapping(
            config.sim_marker_contracts.items(), "simulator marker contracts"
        ),
    }
    schedule_path = _file(config.schedule_manifest, "schedule manifest")
    schedule = _load_object(schedule_path, "schedule manifest")
    schedule_rate = schedule.get("schedule_rate_hz")
    substeps = schedule.get("fixed_substeps_per_tick")
    if (
        isinstance(schedule_rate, bool)
        or not isinstance(schedule_rate, (int, float))
        or isinstance(substeps, bool)
        or not isinstance(substeps, int)
        or substeps <= 0
    ):
        raise SuiteError(
            "schedule manifest lacks numeric rate and fixed substeps per tick"
        )
    physics_rate = float(schedule_rate) * substeps
    if not math.isclose(comparison_fps, physics_rate, abs_tol=1e-12):
        raise SuiteError(
            "comparison_fps must equal the measured schedule physics rate"
        )
    if not math.isclose(config.start_s, -1.0, abs_tol=1e-12):
        raise SuiteError(
            "start_s must retain the isolated trial from neutral tick zero"
        )
    if not math.isclose(config.end_s, 3.0, abs_tol=1e-12):
        raise SuiteError(
            "end_s must retain the isolated trial through its final neutral sample"
        )
    rek_capture_paths = {
        key: _directory(path, f"REK capture {key}")
        for key, path in exact_maps["rek_captures"].items()
    }
    rek_video_paths = {
        key: _file(path, f"REK video {key}")
        for key, path in exact_maps["rek_videos"].items()
    }
    sim_capture_paths = {
        key: _directory(path, f"simulator capture {key}")
        for key, path in exact_maps["sim_captures"].items()
    }
    sim_video_paths = {
        key: _file(path, f"simulator video {key}")
        for key, path in exact_maps["sim_videos"].items()
    }
    for label, paths in (
        ("REK captures", rek_capture_paths.values()),
        ("REK videos", rek_video_paths.values()),
        ("simulator captures", sim_capture_paths.values()),
        ("simulator videos", sim_video_paths.values()),
    ):
        normalized = [os.path.normcase(str(path.resolve())) for path in paths]
        if len(set(normalized)) != len(MOTIONS):
            raise SuiteError(f"{label} must be distinct per motion edge")
    video_hashes = [
        _sha256(path) for path in (*rek_video_paths.values(), *sim_video_paths.values())
    ]
    if len(set(video_hashes)) != len(video_hashes):
        raise SuiteError("every REK and simulator motion video must have distinct bytes")
    return SuiteConfig(
        **{
            **config.__dict__,
            "rek_runs": tuple(
                RekRun(raw, transcript)
                for raw, transcript in zip(raw_paths, transcript_paths)
            ),
            "inventory": _file(config.inventory, "inventory"),
            "schedule_manifest": schedule_path,
            "rek_calibration": _file(config.rek_calibration, "REK calibration"),
            "sim_calibration": _file(
                config.sim_calibration, "simulator calibration"
            ),
            "rek_captures": rek_capture_paths,
            "rek_videos": rek_video_paths,
            "rek_marker_contracts": {
                key: _file(path, f"REK marker contract {key}")
                for key, path in exact_maps["rek_marker_contracts"].items()
            },
            "sim_traces": {
                key: _file(path, f"simulator trace {key}")
                for key, path in exact_maps["sim_traces"].items()
            },
            "sim_captures": sim_capture_paths,
            "sim_videos": sim_video_paths,
            "sim_marker_contracts": {
                key: _file(path, f"simulator marker contract {key}")
                for key, path in exact_maps["sim_marker_contracts"].items()
            },
            "output_dir": output,
        }
    )


def run_suite(config: SuiteConfig) -> tuple[int, dict[str, Any]]:
    config = validate_config(config)
    output = config.output_dir
    output.parent.mkdir(parents=True, exist_ok=True)
    output.mkdir()
    evidence_dir = Path(__file__).resolve().parent
    tools = {
        "client_fixed_import": _file(
            evidence_dir / "client_fixed_import.py", "client-fixed importer"
        ),
        "video_clock_anchor": _file(
            evidence_dir / "video_clock_anchor.py", "video clock anchor tool"
        ),
        "paired_motion_compare": _file(
            evidence_dir / "paired_motion_compare.py", "paired comparator"
        ),
    }
    invocations = InvocationRecorder(output, tools)
    report: dict[str, Any] = {
        "schema": SUITE_SCHEMA,
        "state": "in_progress",
        "passed": None,
        "blockers": [],
        "scope": {
            "motion_set": "six_controlled_fighter_root_velocity_commands",
            "motion_edges": [
                {
                    "selector": motion.selector,
                    "command_identity": motion.command_identity,
                    "simulator_command": motion.simulator_command,
                    "normalized_command": list(motion.normalized_command),
                    "rek_edge_schedule_tick": motion.rek_edge_schedule_tick,
                    "rek_release_schedule_tick": motion.rek_release_schedule_tick,
                    "simulator_trial_scope": "isolated_same_reset_single_press",
                    "simulator_edge_trial_tick": TRIAL_PRESS_TICK,
                    "simulator_release_trial_tick": TRIAL_RELEASE_TICK,
                }
                for motion in MOTIONS
            ],
            "combat_motions_evaluated": False,
            "complete_rek_moveset_claimed": False,
            "opponent_trajectory_evaluated": False,
            "joint_pose_evaluated": False,
            "contact_or_event_parity_evaluated": False,
            "full_trajectory_event_parity_claimed": False,
            "frame_perfect_video_alignment_claimed": False,
            "video_alignment_precision": (
                "machine-measured marker bracket, midpoint estimate with half-source-"
                "frame uncertainty"
            ),
        },
        "acceptance": {
            "accept_at": config.accept_at,
            "start_relative_time_s": config.start_s,
            "end_relative_time_s": config.end_s,
            "comparison_fps": config.comparison_fps,
            "maximum_timestamp_uncertainty_s": (
                config.maximum_timestamp_uncertainty_s
            ),
            "screen_metric_required": config.screen_required,
            "video_fps": config.video_fps,
            "video_layout": config.video_layout,
            "manual_clock_offsets_allowed": False,
            "interpolation_allowed": False,
            "allowance_source": "time-indexed repeated-run REK variance only",
        },
        "tools": {name: _identity(path) for name, path in tools.items()},
        "inputs": {
            "inventory": _identity(config.inventory),
            "schedule_manifest": _identity(config.schedule_manifest),
            "rek_runs": [
                {
                    "raw_trace": _identity(run.raw_trace),
                    "bridge_transcript": _identity(run.bridge_transcript),
                }
                for run in config.rek_runs
            ],
            "rek_captures": {
                selector: {
                    "path": str(config.rek_captures[selector]),
                    "video": _identity(config.rek_videos[selector]),
                }
                for selector in MOTION_SELECTORS
            },
            "rek_marker_contracts": {
                selector: _identity(path)
                for selector, path in config.rek_marker_contracts.items()
            },
        },
        "shared_arena_frame_calibration": None,
        "motions": [],
        "invocations": [],
    }

    try:
        report["shared_arena_frame_calibration"] = validate_shared_calibrations(
            config.rek_calibration, config.sim_calibration
        )
    except Exception as exc:
        report["state"] = "insufficient_evidence"
        report["passed"] = None
        report["blockers"].append({
            "code": "shared_arena_frame_calibration_not_proven",
            "detail": str(exc),
        })
        report["invocations"] = invocations.records
        _write_json_exclusive(output / "suite.report.json", report)
        return 2, report

    simulator_trial_proofs: dict[str, dict[str, Any]] = {}
    simulator_trial_errors: dict[str, str] = {}
    for motion in MOTIONS:
        try:
            simulator_trial_proofs[motion.selector] = (
                validate_simulator_isolated_trial(
                    config.sim_traces[motion.selector],
                    motion,
                    config.start_s,
                    config.end_s,
                )
            )
        except Exception as exc:
            simulator_trial_errors[motion.selector] = str(exc)
    if not simulator_trial_errors:
        reset_record_hashes = {
            proof["reset"]["record_sha256"]
            for proof in simulator_trial_proofs.values()
        }
        reset_identity_hashes = {
            proof["reset"]["identity_sha256"]
            for proof in simulator_trial_proofs.values()
        }
        if len(reset_record_hashes) != 1 or len(reset_identity_hashes) != 1:
            detail = (
                "the six simulator selectors do not start from the exact same "
                "measured composite reset"
            )
            simulator_trial_errors = {
                selector: detail for selector in MOTION_SELECTORS
            }
    report["simulator_single_press_trials"] = {
        selector: (
            {"state": "verified", "proof": simulator_trial_proofs[selector]}
            if selector not in simulator_trial_errors
            else {"state": "insufficient_evidence", "detail": simulator_trial_errors[selector]}
        )
        for selector in MOTION_SELECTORS
    }

    for motion in MOTIONS:
        motion_dir = output / "motions" / motion.slug
        rek_dir = motion_dir / "rek"
        motion_dir.mkdir(parents=True)
        rek_dir.mkdir()
        motion_record: dict[str, Any] = {
            "selector": motion.selector,
            "command_identity": motion.command_identity,
            "state": "in_progress",
            "passed": None,
            "blockers": [],
            "rek_traces": [],
            "sim_trace": _identity(config.sim_traces[motion.selector]),
            "rek_capture_manifest": None,
            "rek_video": _identity(config.rek_videos[motion.selector]),
            "sim_capture_manifest": None,
            "sim_video": _identity(config.sim_videos[motion.selector]),
            "sim_marker_contract": _identity(
                config.sim_marker_contracts[motion.selector]
            ),
            "simulator_isolated_trial": None,
            "video_clock_anchors": None,
            "comparison_report": None,
            "paired_video": None,
        }
        report["motions"].append(motion_record)
        if motion.selector in simulator_trial_errors:
            motion_record["blockers"].append({
                "code": "simulator_isolated_same_reset_single_press_not_proven",
                "detail": simulator_trial_errors[motion.selector],
            })
            motion_record["state"] = "insufficient_evidence"
            continue
        motion_record["simulator_isolated_trial"] = simulator_trial_proofs[
            motion.selector
        ]
        try:
            motion_record["rek_capture_manifest"] = _capture_manifest_identity(
                config.rek_captures[motion.selector],
                CAPTURE_SCHEMA,
                config.rek_videos[motion.selector],
                config.rek_marker_contracts[motion.selector],
                motion.command_identity,
            )
        except Exception as exc:
            motion_record["blockers"].append({
                "code": "rek_capture_not_complete",
                "detail": str(exc),
            })
            motion_record["state"] = "insufficient_evidence"
            continue
        try:
            motion_record["sim_capture_manifest"] = _capture_manifest_identity(
                config.sim_captures[motion.selector],
                SIM_CAPTURE_SCHEMA,
                config.sim_videos[motion.selector],
                config.sim_marker_contracts[motion.selector],
                motion.command_identity,
            )
        except Exception as exc:
            motion_record["blockers"].append({
                "code": "simulator_capture_not_complete",
                "detail": str(exc),
            })
            motion_record["state"] = "insufficient_evidence"
            continue
        rek_capture_record = motion_record["rek_capture_manifest"]
        sim_capture_record = motion_record["sim_capture_manifest"]
        rek_capture_rate = (
            rek_capture_record["fps_numerator"]
            / rek_capture_record["fps_denominator"]
        )
        sim_capture_rate = (
            sim_capture_record["fps_numerator"]
            / sim_capture_record["fps_denominator"]
        )
        if (
            (rek_capture_record["width_px"], rek_capture_record["height_px"])
            != (sim_capture_record["width_px"], sim_capture_record["height_px"])
            or not math.isclose(rek_capture_rate, sim_capture_rate, abs_tol=1e-12)
            or not math.isclose(rek_capture_rate, config.video_fps, abs_tol=1e-12)
        ):
            motion_record["blockers"].append({
                "code": "motion_video_geometry_or_rate_not_identical",
                "rek": {
                    "width_px": rek_capture_record["width_px"],
                    "height_px": rek_capture_record["height_px"],
                    "fps": rek_capture_rate,
                },
                "simulator": {
                    "width_px": sim_capture_record["width_px"],
                    "height_px": sim_capture_record["height_px"],
                    "fps": sim_capture_rate,
                },
            })
            motion_record["state"] = "insufficient_evidence"
            continue
        imported: list[Path] = []
        for index, run in enumerate(config.rek_runs, 1):
            imported_path = rek_dir / f"run-{index}.rektrace"
            result = invocations.run(
                "client_fixed_import",
                (
                    "--raw", str(run.raw_trace),
                    "--inventory", str(config.inventory),
                    "--out", str(imported_path),
                    "--control-log", str(run.bridge_transcript),
                    "--schedule-manifest", str(config.schedule_manifest),
                    "--motion-edge", motion.selector,
                ),
                f"import-{motion.slug}-run-{index}",
            )
            if result.exit_code != 0 or not imported_path.is_file():
                motion_record["blockers"].append({
                    "code": "rek_v6_import_failed",
                    "run_index": index,
                    "tool_exit_code": result.exit_code,
                    "invocation": result.record["record_path"],
                })
            else:
                imported.append(imported_path)
                motion_record["rek_traces"].append(_identity(imported_path))
        if len(imported) != len(config.rek_runs):
            motion_record["state"] = "insufficient_evidence"
            continue

        try:
            sim_inline = validate_simulator_trace_calibration(
                config.sim_traces[motion.selector],
                config.sim_calibration,
                motion.command_identity,
            )
        except Exception as exc:
            motion_record["blockers"].append({
                "code": "simulator_trace_calibration_not_explicitly_bound",
                "detail": str(exc),
            })
            motion_record["state"] = "insufficient_evidence"
            continue
        motion_record["simulator_calibration_source"] = (
            "inline_exactly_equals_explicit_calibration"
            if sim_inline else "explicit_calibration_file"
        )

        preflight_path = motion_dir / "preflight.comparison.json"
        preflight = invocations.run(
            "paired_motion_compare",
            _comparison_arguments(
                config,
                imported,
                config.sim_traces[motion.selector],
                preflight_path,
                sim_has_inline_calibration=sim_inline,
            ),
            f"compare-preflight-{motion.slug}",
        )
        try:
            state, preflight_report = _validate_preflight_report(
                preflight_path,
                motion,
                preflight.exit_code,
                config,
                imported,
                config.sim_traces[motion.selector],
            )
        except Exception as exc:
            motion_record["blockers"].append({
                "code": "preflight_comparator_output_invalid",
                "detail": str(exc),
                "tool_exit_code": preflight.exit_code,
            })
            motion_record["state"] = "insufficient_evidence"
            continue
        motion_record["preflight_report"] = _identity(preflight_path)
        if state != "passed":
            motion_record["state"] = state
            motion_record["passed"] = preflight_report["verdict"]["passed"]
            motion_record["blockers"] = preflight_report["verdict"]["blockers"]
            motion_record["comparison_report"] = _identity(preflight_path)
            continue

        rek_anchor_path = motion_dir / "rek.video-clock-anchor.json"
        sim_anchor_path = motion_dir / "sim.video-clock-anchor.json"
        rek_anchor_result = invocations.run(
            "video_clock_anchor",
            (
                "--capture", str(config.rek_captures[motion.selector]),
                "--marker-contract",
                str(config.rek_marker_contracts[motion.selector]),
                "--out", str(rek_anchor_path),
            ),
            f"anchor-rek-{motion.slug}",
        )
        sim_anchor_result = invocations.run(
            "video_clock_anchor",
            (
                "--capture", str(config.sim_captures[motion.selector]),
                "--marker-contract",
                str(config.sim_marker_contracts[motion.selector]),
                "--out", str(sim_anchor_path),
            ),
            f"anchor-sim-{motion.slug}",
        )
        if rek_anchor_result.exit_code != 0 or sim_anchor_result.exit_code != 0:
            motion_record["blockers"].append({
                "code": "measured_video_clock_anchor_failed",
                "rek_exit_code": rek_anchor_result.exit_code,
                "sim_exit_code": sim_anchor_result.exit_code,
            })
            motion_record["state"] = "insufficient_evidence"
            continue
        try:
            _validate_generated_anchor(
                rek_anchor_path,
                imported[0],
                config.rek_videos[motion.selector],
                config.rek_captures[motion.selector],
                config.rek_marker_contracts[motion.selector],
                CAPTURE_SCHEMA,
                motion.command_identity,
            )
            _validate_generated_anchor(
                sim_anchor_path,
                config.sim_traces[motion.selector],
                config.sim_videos[motion.selector],
                config.sim_captures[motion.selector],
                config.sim_marker_contracts[motion.selector],
                SIM_CAPTURE_SCHEMA,
                motion.command_identity,
            )
            motion_record["video_clock_anchors"] = {
                "rek": _identity(rek_anchor_path),
                "simulator": _identity(sim_anchor_path),
            }
        except Exception as exc:
            motion_record["blockers"].append({
                "code": "diagnostic_manual_or_unbound_video_anchor_refused",
                "detail": str(exc),
            })
            motion_record["state"] = "insufficient_evidence"
            continue

        final_path = motion_dir / "comparison.json"
        clip_path = motion_dir / "paired.mp4"
        final = invocations.run(
            "paired_motion_compare",
            _comparison_arguments(
                config,
                imported,
                config.sim_traces[motion.selector],
                final_path,
                sim_has_inline_calibration=sim_inline,
                rek_video=config.rek_videos[motion.selector],
                sim_video=config.sim_videos[motion.selector],
                video_out=clip_path,
                rek_anchor=rek_anchor_path,
                sim_anchor=sim_anchor_path,
            ),
            f"compare-video-{motion.slug}",
        )
        if final.exit_code != 0:
            if clip_path.is_file():
                motion_record["discarded_unaccepted_clip_sha256"] = _sha256(
                    clip_path
                )
                clip_path.unlink()
            motion_record["blockers"].append({
                "code": "acceptance_video_comparison_failed",
                "tool_exit_code": final.exit_code,
            })
            motion_record["state"] = "insufficient_evidence"
            continue
        try:
            final_report = _validate_final_report(
                final_path,
                clip_path,
                motion,
                config,
                imported,
                config.sim_traces[motion.selector],
                config.rek_videos[motion.selector],
                config.sim_videos[motion.selector],
            )
        except Exception as exc:
            if clip_path.is_file():
                motion_record["discarded_unaccepted_clip_sha256"] = _sha256(
                    clip_path
                )
                clip_path.unlink()
            motion_record["blockers"].append({
                "code": "acceptance_video_report_invalid",
                "detail": str(exc),
            })
            motion_record["state"] = "insufficient_evidence"
            continue
        motion_record["state"] = "passed"
        motion_record["passed"] = True
        motion_record["comparison_report"] = _identity(final_path)
        motion_record["paired_video"] = _identity(clip_path)
        motion_record["metrics"] = final_report["metrics"]

    states = [motion["state"] for motion in report["motions"]]
    if all(state == "passed" for state in states):
        report["state"] = "passed"
        report["passed"] = True
    elif any(state == "insufficient_evidence" for state in states):
        report["state"] = "insufficient_evidence"
        report["passed"] = None
        report["blockers"].append("one_or_more_motion_edges_lack_acceptance_evidence")
    else:
        report["state"] = "failed"
        report["passed"] = False
        report["blockers"].append("one_or_more_motion_edges_exceed_rek_variance")
    report["invocations"] = [
        {
            "sequence": record["sequence"],
            "label": record["label"],
            "exit_code": record["exit_code"],
            "record_path": record["record_path"],
            "record_sha256": record["record_sha256"],
        }
        for record in invocations.records
    ]
    suite_path = output / "suite.report.json"
    _write_json_exclusive(suite_path, report)
    print(f"suite: {report['state']}")
    print(f"motions: {len(report['motions'])}")
    print(f"report: {suite_path.resolve()}")
    print(f"report sha256: {_sha256(suite_path)}")
    if report["passed"] is True:
        return 0, report
    if report["passed"] is False:
        return 1, report
    return 2, report


