def config_from_args(arguments: argparse.Namespace) -> SuiteConfig:
    return SuiteConfig(
        rek_runs=tuple(
            RekRun(Path(raw), Path(transcript))
            for raw, transcript in arguments.rek_run
        ),
        inventory=arguments.inventory,
        schedule_manifest=arguments.schedule_manifest,
        rek_calibration=arguments.rek_calibration,
        sim_calibration=arguments.sim_calibration,
        rek_pilot=arguments.rek_pilot,
        sim_pilot=arguments.sim_pilot,
        rek_captures=_mapping(arguments.rek_capture, "REK captures"),
        rek_videos=_mapping(arguments.rek_video, "REK videos"),
        rek_marker_contracts=_mapping(
            arguments.rek_marker_contract, "REK marker contracts"
        ),
        sim_traces=_mapping(arguments.sim_trace, "simulator traces"),
        sim_captures=_mapping(arguments.sim_capture, "simulator captures"),
        sim_videos=_mapping(arguments.sim_video, "simulator videos"),
        sim_marker_contracts=_mapping(
            arguments.sim_marker_contract, "simulator marker contracts"
        ),
        output_dir=arguments.out,
        accept_at=arguments.accept_at,
        start_s=arguments.start_s,
        end_s=arguments.end_s,
        comparison_fps=arguments.comparison_fps,
        maximum_timestamp_uncertainty_s=arguments.max_timestamp_uncertainty_s,
        screen_required=arguments.screen_gate == "required",
        video_fps=arguments.video_fps,
        video_layout=arguments.video_layout,
    )


def main(argv: Sequence[str] | None = None) -> int:
    try:
        arguments = build_parser().parse_args(argv)
        config = config_from_args(arguments)
        exit_code, _ = run_suite(config)
        return exit_code
    except (FileExistsError, OSError, SuiteError, ValueError) as exc:
        print(f"motion parity suite failed: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
